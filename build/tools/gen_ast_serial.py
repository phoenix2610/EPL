#!/usr/bin/env python3
"""
Generate ast_serial.inc — a field-level description of every AST node type,
used by epc.c to read and write .EPC parsed-AST caches.

Derived directly from ast.h so the serializer can never drift from the struct
layout. Each union member in ast.h is tagged with the NodeType(s) it serves via
a preceding /* NODE_X */ comment; this script reads those tags, enumerates the
member's fields, and emits an offsetof-based descriptor table.

Run from build/:   python3 tools/gen_ast_serial.py
"""
import re, sys, os, hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
AST_H = os.path.join(HERE, "..", "ast.h")
OUT   = os.path.join(HERE, "..", "ast_serial.inc")
SIZES = os.path.join(HERE, "..", "ast_sizes.inc")

SCALARS = {"int": "int", "double": "double"}
ENUMS = {"TokenType", "PanelPosition", "CollectionOp", "StringOp", "FormatOp",
         "TypeCheckKind", "EPFTheme", "ChartType", "Background3D", "Node3DStatus"}

def main():
    src = open(AST_H).read()
    union = src[src.index("union {"): src.rindex("} as;")]

    e = src[src.index("typedef enum"):]
    e = e[:e.index("} NodeType")]
    all_types = re.findall(r"^\s*(NODE_[A-Z0-9_]+)\s*[,=]", e, re.M)

    member_pat = re.compile(
        r"/\*\s*(NODE_[A-Z0-9_]+(?:\s*[/,]\s*NODE_[A-Z0-9_]+)*)[^*]*\*/\s*"
        r"struct\s*\{(.*?)\}\s*(\w+)\s*;", re.S)

    descs = {}
    for m in member_pat.finditer(union):
        types  = re.findall(r"NODE_[A-Z0-9_]+", m.group(1))
        body, member = m.group(2), m.group(3)
        fields = []
        for raw in body.split("\n"):
            line = re.sub(r"/\*.*?\*/", "", raw).strip().rstrip(";").strip()
            if not line:
                continue
            mm = re.match(r"([A-Za-z_][\w\s]*?)\s*(\*?)\s*(\w+)\s*(\[[^\]]*\])?$", line)
            if not mm:
                sys.exit(f"gen_ast_serial: cannot parse field: {line!r}")
            ty, star, name, arr = mm.group(1).strip(), mm.group(2), mm.group(3), mm.group(4)
            if ty == "ASTNode" and star == "*":
                fields.append(("F_NODE", name, "0"))
            elif ty == "NodeList":
                fields.append(("F_LIST", name, "0"))
            elif ty == "char" and arr:
                fields.append(("F_STR", name, f"sizeof(((ASTNode*)0)->as.{member}.{name})"))
            elif ty in SCALARS or ty in ENUMS:
                fields.append(("F_RAW", name, f"sizeof(((ASTNode*)0)->as.{member}.{name})"))
            else:
                sys.exit(f"gen_ast_serial: unknown field type {ty!r} in {member}.{name}")
        for t in types:
            descs[t] = (member, fields)

    missing = [t for t in all_types if t not in descs]

    out = []
    out.append("/* GENERATED by tools/gen_ast_serial.py — do not edit by hand.")
    out.append("   Field-level layout of every AST node, used by epc.c. */")
    out.append("")
    out.append("typedef enum { F_STR, F_RAW, F_NODE, F_LIST } FKind;")
    out.append("typedef struct { unsigned char kind; unsigned int off; unsigned int size; } FDesc;")
    out.append("")
    for t in all_types:
        if t not in descs:
            continue
        member, fields = descs[t]
        if not fields:
            continue
        out.append(f"static const FDesc FD_{t}[] = {{")
        for kind, name, size in fields:
            out.append(f"    {{ {kind}, offsetof(ASTNode, as.{member}.{name}), {size} }},")
        out.append("};")
    out.append("")
    out.append("typedef struct { const FDesc *f; unsigned int n; } NodeDesc;")
    out.append("static const NodeDesc AST_DESC[] = {")
    for t in all_types:
        if t in descs and descs[t][1]:
            out.append(f"    [{t}] = {{ FD_{t}, (unsigned int)(sizeof(FD_{t})/sizeof(FDesc)) }},")
        else:
            out.append(f"    [{t}] = {{ 0, 0 }},   /* no payload */")
    out.append("};")
    out.append("")
    out.append(f"#define AST_DESC_COUNT {len(all_types)}")
    digest = hashlib.sha256(open(AST_H, 'rb').read()).hexdigest()[:16]
    out.append(f'#define AST_LAYOUT_HASH 0x{digest[:8]}u')
    text = "\n".join(out) + "\n"

    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT)}")

    sizes = ["/* GENERATED by tools/gen_ast_serial.py — do not edit by hand.",
             "   Bytes to allocate for each AST node type (see ast_make_node). */",
             "", "static const unsigned int AST_NODE_SIZE[] = {"]
    for t in all_types:
        if t in descs:
            member = descs[t][0]
            sizes.append(f"    [{t}] = (unsigned int)(offsetof(ASTNode, as) + "
                         f"sizeof(((ASTNode*)0)->as.{member})),")
        else:
            sizes.append(f"    [{t}] = (unsigned int)sizeof(ASTNode),")
    sizes.append("};")
    sizes.append(f"#define AST_NODE_SIZE_COUNT {len(all_types)}")
    open(SIZES, "w").write("\n".join(sizes) + "\n")
    print(f"wrote {os.path.relpath(SIZES)}")
    print(f"  node types      : {len(all_types)}")
    print(f"  with payload    : {sum(1 for t in all_types if t in descs and descs[t][1])}")
    print(f"  payload-free    : {len(all_types) - sum(1 for t in all_types if t in descs and descs[t][1])}")
    if missing:
        print(f"  untagged (treated as payload-free): {', '.join(missing)}")

if __name__ == "__main__":
    main()
